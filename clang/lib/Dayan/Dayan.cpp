bool splitSource(const SplitOptions &Options, SplitOutput &Output) {
  const std::string DeviceTriple = Options.DeviceTriple.empty()
                                       ? "riscv64-unknown-elf"
                                       : Options.DeviceTriple;
  const std::string DeviceArch = Options.DeviceArch.empty()
                                     ? "rv64imaf_zicsr_zifencei"
                                     : Options.DeviceArch;
  std::vector<std::string> Arguments = {
      "-x",
      "c++",
      "-std=c++17",
      "-fsyntax-only",
      "--target=" + DeviceTriple,
      "-march=" + DeviceArch,
      "-mabi=lp64",
      "-Xclang",
      "-target-feature",
      "-Xclang",
      "+txlsu",
      "-Xclang",
      "-target-feature",
      "-Xclang",
      "+txmat",
      "-Xclang",
      "-target-feature",
      "-Xclang",
      "+txvec",
      "-Xclang",
      "-target-feature",
      "-Xclang",
      "+txbase",
      "-Xclang",
      "-target-feature",
      "-Xclang",
      "+txmacro",
      "-Wno-ignored-attributes",
      "-D__DAYAN_DEVICE__=1",
      "-include",
      Options.CompilerAttributesHeader,
      "-isystem",
      Options.DeviceAPIInclude,
      "-isystem",
      Options.HostInclude,
  };
  if (!Options.CompilerResourceDir.empty())
    Arguments.insert(Arguments.end(),
                     {"-resource-dir", Options.CompilerResourceDir});
  Arguments.insert(Arguments.end(), Options.CommonArgs.begin(),
                   Options.CommonArgs.end());
  Arguments.insert(Arguments.end(), Options.DeviceArgs.begin(),
                   Options.DeviceArgs.end());

  SplitState State;
  Output.Kernels.clear();
  clang::tooling::FixedCompilationDatabase Database(Options.WorkingDirectory,
                                                    Arguments);
  clang::tooling::ClangTool Tool(Database, {Options.InputPath});
  SplitActionFactory Factory(State, Output, Options.InputPath);
  int Status = Tool.run(&Factory);
  if (Status != 0 || State.failed)
    return false;
  Output.Host = std::move(State.host);
  Output.Device = std::move(State.device);
  return true;
}

