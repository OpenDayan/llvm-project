struct SplitState {
  std::string host;
  std::string device;
  bool failed = false;
};

enum class Side {
  Both,
  Host,
  Device,
  Kernel,
  Invalid,
};

struct Edit {
  std::size_t begin;
  std::size_t end;
  std::string replacement;
};

static Side annotation_side(const Decl *decl) {
  Side result = Side::Both;
  for (const auto *attr : decl->specific_attrs<AnnotateAttr>()) {
    Side current = Side::Both;
    if (attr->getAnnotation() == "dayan.host")
      current = Side::Host;
    else if (attr->getAnnotation() == "dayan.device")
      current = Side::Device;
    else if (attr->getAnnotation() == "dayan.kernel")
      current = Side::Kernel;
    if (current == Side::Both)
      continue;
    if (result != Side::Both && result != current)
      return Side::Invalid;
    result = current;
  }
  return result;
}

static Side function_side(const FunctionDecl *decl) {
  Side result = Side::Both;
  for (const FunctionDecl *redecl : decl->redecls()) {
    Side current = annotation_side(redecl);
    if (current == Side::Invalid)
      return current;
    if (current == Side::Both)
      continue;
    if (result != Side::Both && result != current)
      return Side::Invalid;
    result = current;
  }
  return result;
}

class SplitVisitor : public RecursiveASTVisitor<SplitVisitor> {
public:
  SplitVisitor(ASTContext &context, SplitState &output,
               clang::dayan::SplitOutput &split_output,
               const std::string &input_name)
      : context_(context), source_(context.getSourceManager()),
        language_(context.getLangOpts()), output_(output),
        split_output_(split_output), input_name_(input_name),
        policy_(context.getLangOpts()) {
    policy_.SuppressTagKeyword = false;
    policy_.FullyQualifiedName = true;
    policy_.PrintAsCanonical = false;
  }

  bool VisitFunctionDecl(FunctionDecl *decl) {
    if (!is_main_file_decl(decl) || decl->isImplicit() ||
        !decl->getDeclContext()->getRedeclContext()->isFileContext())
      return true;
    functions_.push_back(decl);
    return true;
  }

  bool VisitVarDecl(VarDecl *decl) {
    if (!is_main_file_decl(decl) || decl->isImplicit() ||
        !decl->isFileVarDecl())
      return true;
    variables_.push_back(decl);
    return true;
  }

  void finish() {
    collect_resource_descriptors();
    if (output_.failed)
      return;
    collect_function_edits();
    collect_variable_edits();
    if (output_.failed)
      return;

    std::string original = source_.getBufferData(source_.getMainFileID()).str();
    output_.host = apply_edits(original, host_edits_, "Host");
    output_.device = apply_edits(original, device_edits_, "Device");
    if (output_.failed)
      return;

    std::ostringstream prelude;
    prelude << "/* Generated by dycc. */\n"
            << "#include <dayan_kernel.h>\n"
            << "extern \"C\" {\n"
            << "extern const unsigned char __kernel_obj__[];\n"
            << "extern const size_t __kernel_obj_size__;\n"
            << "}\n"
            << "#line 1 \"" << escape_string(input_name_) << "\"\n";
    output_.host.insert(0, prelude.str());
    output_.device.insert(0, "/* Generated by dycc. */\n#line 1 \"" +
                                 escape_string(input_name_) + "\"\n");
  }

private:
  struct KernelResources {
    uint32_t max_child_threads = 0;
    uint32_t max_tasks_per_core = 0;
    uint32_t flags = 0;
    uint32_t lsu_tcsr_count = 0;
    uint32_t mat_tcsr_count = 0;
    uint32_t vec_tcsr_count = 0;
    uint32_t macro_tcsr_count = 0;
    uint64_t atomic_cache_size = 0;
    uint64_t uram_size = 0;
  };

  struct Span {
    std::size_t begin;
    std::size_t end;
  };

  bool is_main_file_decl(const Decl *decl) const {
    SourceLocation location = source_.getExpansionLoc(decl->getBeginLoc());
    return location.isValid() && source_.isWrittenInMainFile(location);
  }

  void diagnose(const Decl *decl, const std::string &message) {
    unsigned id = context_.getDiagnostics().getCustomDiagID(
        DiagnosticsEngine::Error, "%0");
    context_.getDiagnostics().Report(decl->getLocation(), id) << message;
    output_.failed = true;
  }

  std::optional<Span> declaration_span(const Decl *decl,
                                       bool consume_semicolon) {
    const Decl *range_decl = decl;
    if (const auto *linkage = llvm::dyn_cast<clang::LinkageSpecDecl>(
            decl->getLexicalDeclContext())) {
      if (!linkage->hasBraces())
        range_decl = linkage;
    }
    SourceLocation begin = source_.getExpansionLoc(range_decl->getBeginLoc());
    SourceLocation end = source_.getExpansionLoc(decl->getEndLoc());
    if (begin.isInvalid() || end.isInvalid() ||
        !source_.isWrittenInMainFile(begin) ||
        !source_.isWrittenInMainFile(end)) {
      diagnose(decl, "dycc cannot rewrite a declaration produced by a macro");
      return std::nullopt;
    }
    SourceLocation after =
        Lexer::getLocForEndOfToken(end, 0, source_, language_);
    if (after.isInvalid()) {
      diagnose(decl, "dycc cannot determine the end of this declaration");
      return std::nullopt;
    }
    if (consume_semicolon) {
      auto next = Lexer::findNextToken(end, source_, language_);
      if (next && next->is(clang::tok::semi)) {
        after = Lexer::getLocForEndOfToken(next->getLocation(), 0, source_,
                                           language_);
      }
    }
    std::size_t begin_offset = source_.getFileOffset(begin);
    std::size_t end_offset = source_.getFileOffset(after);
    if (begin_offset >= end_offset) {
      diagnose(decl, "dycc computed an invalid declaration source range");
      return std::nullopt;
    }
    return Span{begin_offset, end_offset};
  }

  std::optional<Span> variable_statement_span(const VarDecl *decl) {
    auto span = declaration_span(decl, false);
    unsigned brace_depth = 0;
    unsigned bracket_depth = 0;
    unsigned parenthesis_depth = 0;

    if (!span)
      return std::nullopt;
    SourceLocation cursor = source_.getExpansionLoc(decl->getEndLoc());
    for (;;) {
      auto next = Lexer::findNextToken(cursor, source_, language_);
      if (!next) {
        diagnose(decl,
                 "dycc cannot find ';' after global variable declaration");
        return std::nullopt;
      }
      cursor = next->getLocation();
      if (next->is(clang::tok::semi) && !brace_depth && !bracket_depth &&
          !parenthesis_depth) {
        SourceLocation after =
            Lexer::getLocForEndOfToken(cursor, 0, source_, language_);
        span->end = source_.getFileOffset(after);
        return span;
      }
      if (next->is(clang::tok::l_brace))
        ++brace_depth;
      else if (next->is(clang::tok::l_square))
        ++bracket_depth;
      else if (next->is(clang::tok::l_paren))
        ++parenthesis_depth;
      else if (next->is(clang::tok::r_brace) && brace_depth)
        --brace_depth;
      else if (next->is(clang::tok::r_square) && bracket_depth)
        --bracket_depth;
      else if (next->is(clang::tok::r_paren) && parenthesis_depth)
        --parenthesis_depth;
      else if (next->is(clang::tok::r_brace) ||
               next->is(clang::tok::r_square) ||
               next->is(clang::tok::r_paren)) {
        diagnose(decl, "dycc cannot isolate this global variable declaration");
        return std::nullopt;
      }
    }
  }

  std::optional<Span> skipped_function_span(const FunctionDecl *decl) {
    auto span = declaration_span(decl, false);
    SourceLocation cursor = source_.getExpansionLoc(decl->getEndLoc());
    unsigned depth = 0;

    if (!span)
      return std::nullopt;
    for (;;) {
      auto next = Lexer::findNextToken(cursor, source_, language_);
      if (!next) {
        diagnose(decl, "dycc cannot find the skipped function body");
        return std::nullopt;
      }
      cursor = next->getLocation();
      if (!depth) {
        if (next->is(clang::tok::semi) || next->is(clang::tok::r_brace)) {
          diagnose(decl, "dycc cannot find the skipped function body");
          return std::nullopt;
        }
        if (next->is(clang::tok::l_brace))
          depth = 1;
        continue;
      }
      if (next->is(clang::tok::l_brace)) {
        ++depth;
      } else if (next->is(clang::tok::r_brace) && --depth == 0) {
        SourceLocation after =
            Lexer::getLocForEndOfToken(cursor, 0, source_, language_);
        span->end = source_.getFileOffset(after);
        return span;
      }
    }
  }

  static std::string escape_string(const std::string &value) {
    std::string escaped;
    for (char c : value) {
      if (c == '\\' || c == '"')
        escaped.push_back('\\');
      escaped.push_back(c);
    }
    return escaped;
  }

  std::string source_text(SourceRange range) const {
    if (range.isInvalid())
      return {};
    return Lexer::getSourceText(CharSourceRange::getTokenRange(range), source_,
                                language_)
        .str();
  }

  std::string parameter_declaration(const ParmVarDecl *parameter,
                                    unsigned index, bool with_default) {
    std::string name = parameter->getNameAsString();
    if (name.empty())
      name = "__dayan_arg_" + std::to_string(index);
    QualType canonical = parameter->getType().getCanonicalType();
    std::string rendered;
    if (canonical->isReferenceType() || canonical->isPointerType()) {
      rendered = "::npu_buffer_t *" + name;
      return rendered;
    }
    llvm::raw_string_ostream stream(rendered);
    parameter->getOriginalType().print(stream, policy_, name);
    stream.flush();
    if (with_default && parameter->hasDefaultArg() &&
        !parameter->hasInheritedDefaultArg()) {
      std::string expression = source_text(parameter->getDefaultArgRange());
      if (!expression.empty())
        rendered += " = " + expression;
    }
    return rendered;
  }

  std::string argument_expression(const ParmVarDecl *parameter,
                                  unsigned index) {
    std::string name = parameter->getNameAsString();
    if (name.empty())
      name = "__dayan_arg_" + std::to_string(index);
    QualType type = parameter->getType();
    QualType canonical = type.getCanonicalType();
    if (canonical->isReferenceType() || canonical->isPointerType())
      return name;
    if (canonical->isNullPtrType())
      return "UINT64_C(0)";
    if (canonical->isIntegralOrEnumerationType())
      return "static_cast<uint64_t>(" + name + ")";
    if (canonical->isSpecificBuiltinType(clang::BuiltinType::Float))
      return "::npu_kernel_pack_f32(" + name + ")";
    if (canonical->isSpecificBuiltinType(clang::BuiltinType::Double))
      return "::npu_kernel_pack_f64(" + name + ")";
    return {};
  }

  bool buffer_parameter(const ParmVarDecl *parameter) const {
    QualType canonical = parameter->getType().getCanonicalType();
    return canonical->isReferenceType() || canonical->isPointerType();
  }

  uint64_t argument_size(const ParmVarDecl *parameter) const {
    QualType canonical = parameter->getType().getCanonicalType();
    if (buffer_parameter(parameter) || canonical->isNullPtrType())
      return 8;
    return static_cast<uint64_t>(
        context_.getTypeSizeInChars(canonical).getQuantity());
  }

  uint64_t buffer_alignment(const ParmVarDecl *parameter) const {
    QualType canonical = parameter->getType().getCanonicalType();
    QualType pointee = canonical->getPointeeType();
    if (pointee.isNull() || pointee->isVoidType() ||
        pointee->isFunctionType() || pointee->isIncompleteType())
      return 1;
    return static_cast<uint64_t>(
        context_.getTypeAlignInChars(pointee).getQuantity());
  }

  uint32_t buffer_access(const ParmVarDecl *parameter) const {
    QualType pointee =
        parameter->getType().getCanonicalType()->getPointeeType();
    return pointee.isConstQualified() ? 1U : 3U;
  }

  clang::dayan::PackageArgumentInfo
  package_argument(const ParmVarDecl *parameter) const {
    clang::dayan::PackageArgumentInfo argument;
    if (buffer_parameter(parameter)) {
      argument.Kind = 2U;
      argument.Size = 8U;
      argument.Alignment = static_cast<uint32_t>(buffer_alignment(parameter));
      argument.Access = buffer_access(parameter);
    } else {
      argument.Kind = 1U;
      argument.Size = static_cast<uint32_t>(argument_size(parameter));
    }
    return argument;
  }

  std::string mangled_name(const FunctionDecl *decl) {
    std::unique_ptr<MangleContext> mangler(context_.createMangleContext());
    if (!mangler->shouldMangleDeclName(decl))
      return decl->getNameAsString();
    std::string result;
    llvm::raw_string_ostream stream(result);
    mangler->mangleName(GlobalDecl(decl), stream);
    stream.flush();
    return result;
  }

  bool constant_uint64(const clang::Expr *expression, uint64_t &value) {
    clang::Expr::EvalResult result;

    if (!expression || !expression->EvaluateAsInt(result, context_) ||
        !result.Val.isInt())
      return false;
    const llvm::APSInt &integer = result.Val.getInt();
    if ((integer.isSigned() && integer.isNegative()) ||
        integer.getActiveBits() > 64)
      return false;
    value = integer.getZExtValue();
    return true;
  }

  bool evaluate_resource_descriptor(VarDecl *decl, KernelResources &resources) {
    const clang::Expr *initializer = decl->getInit();
    const auto *list = initializer ? llvm::dyn_cast<clang::InitListExpr>(
                                         initializer->IgnoreParenImpCasts())
                                   : nullptr;
    uint64_t fields[10];
    unsigned index;

    if (!decl->getType().isConstQualified() ||
        context_.getTypeSizeInChars(decl->getType()).getQuantity() != 32 ||
        decl->getFormalLinkage() == clang::Linkage::Internal ||
        !decl->isInExternCContext()) {
      diagnose(decl, "kernel resource descriptor must be a 32-byte "
                     "extern C const object");
      return false;
    }
    if (list && list->isSyntacticForm())
      list = list->getSemanticForm();
    if (!list || list->getNumInits() != 10) {
      diagnose(decl, "kernel resource descriptor requires ten "
                     "constant fields");
      return false;
    }
    for (index = 0; index < 10; ++index) {
      if (!constant_uint64(list->getInit(index), fields[index])) {
        diagnose(decl, "kernel resource descriptor fields must be "
                       "non-negative integer constants");
        return false;
      }
    }
    if (fields[0] > 15U || fields[1] > 4U || (fields[2] & ~UINT64_C(1)) ||
        ((fields[2] & UINT64_C(1)) && fields[1] > 1U) || fields[3] > 8U ||
        fields[4] > 8U || fields[5] > 8U || fields[6] > 8U || fields[7] ||
        (fields[9] & 32767U)) {
      diagnose(decl, "invalid kernel resources: expected "
                     "child_threads<=15, tasks_per_core<=4, "
                     "known flags, locked_task tasks_per_core<=1, "
                     "TCSR counts<=8 and 32 KiB-aligned URAM size");
      return false;
    }
    resources.max_child_threads = static_cast<uint32_t>(fields[0]);
    resources.max_tasks_per_core = static_cast<uint32_t>(fields[1]);
    resources.flags = static_cast<uint32_t>(fields[2]);
    resources.lsu_tcsr_count = static_cast<uint32_t>(fields[3]);
    resources.mat_tcsr_count = static_cast<uint32_t>(fields[4]);
    resources.vec_tcsr_count = static_cast<uint32_t>(fields[5]);
    resources.macro_tcsr_count = static_cast<uint32_t>(fields[6]);
    resources.atomic_cache_size = fields[8];
    resources.uram_size = fields[9];
    return true;
  }

  void collect_resource_descriptors() {
    std::map<std::string, const FunctionDecl *> kernels;
    std::set<const FunctionDecl *> seen;

    for (FunctionDecl *decl : functions_) {
      const FunctionDecl *canonical = decl->getCanonicalDecl();

      if (function_side(decl) != Side::Kernel ||
          !seen.insert(canonical).second || !decl->getIdentifier())
        continue;
      std::string name = decl->getNameAsString();
      auto [position, inserted] = kernels.emplace(name, canonical);

      if (!inserted && position->second != canonical)
        diagnose(decl, "overloaded __kernel__ names cannot share the "
                       "required <kernel>__desc symbol");
    }
    for (const auto &[name, kernel] : kernels) {
      std::string descriptor_name = name + "__desc";
      VarDecl *found = nullptr;

      (void)kernel;
      for (VarDecl *candidate : variables_) {
        if (candidate->getNameAsString() != descriptor_name ||
            !candidate->isThisDeclarationADefinition())
          continue;
        if (found) {
          diagnose(candidate, "duplicate kernel resource descriptor '" +
                                  descriptor_name + "'");
          continue;
        }
        found = candidate;
      }
      if (!found) {
        diagnose(const_cast<FunctionDecl *>(kernel),
                 "__kernel__ requires a resource descriptor for '" + name +
                     "': DAYAN_KERNEL_DESC, "
                     "DAYAN_KERNEL_TASK_DESC, or "
                     "DAYAN_KERNEL_LOCKED_TASK_DESC");
        continue;
      }
      if (annotation_side(found) != Side::Device) {
        diagnose(found, "kernel resource descriptor must be Device-only");
        continue;
      }
      KernelResources resources;
      if (!evaluate_resource_descriptor(found, resources))
        continue;
      kernel_resources_[name] = resources;
      descriptor_variables_.insert(found);
    }
  }

  std::string wrapper(const FunctionDecl *decl, bool definition) {
    std::ostringstream out;
    const KernelResources &resources =
        kernel_resources_.at(decl->getNameAsString());
    unsigned line = source_.getSpellingLineNumber(
        source_.getExpansionLoc(decl->getBeginLoc()));
    unsigned after_line = source_.getSpellingLineNumber(
                              source_.getExpansionLoc(decl->getEndLoc())) +
                          1;
    const auto *linkage =
        llvm::dyn_cast<clang::LinkageSpecDecl>(decl->getLexicalDeclContext());
    out << "#line " << line << " \"" << escape_string(input_name_) << "\"\n";
    if (linkage && !linkage->hasBraces())
      out << "extern \"C\" ";
    out << "int " << decl->getNameAsString() << "(";
    for (unsigned i = 0; i < decl->getNumParams(); ++i) {
      if (i)
        out << ", ";
      out << parameter_declaration(decl->getParamDecl(i), i, false);
    }
    if (decl->getNumParams())
      out << ", ";
    out << "const ::npu_kernel_launch_attrs_t *__dayan_launch_attrs)";
    if (!definition) {
      out << ";\n#line " << after_line << " \"" << escape_string(input_name_)
          << "\"\n";
      return out.str();
    }

    out << "\n{\n"
        << "    static ::npu_kernel_descriptor_t *__dayan_descriptor = "
           "nullptr;\n"
        << "    static unsigned char __dayan_init_lock = 0;\n"
        << "    static const ::dayan_kernel_resource_desc_t "
           "__dayan_resources = {\n"
        << "        " << resources.max_child_threads << "U, "
        << resources.max_tasks_per_core << "U, " << resources.flags << "U, "
        << resources.lsu_tcsr_count << "U, " << resources.mat_tcsr_count
        << "U, " << resources.vec_tcsr_count << "U, "
        << resources.macro_tcsr_count << "U, 0U, UINT64_C("
        << resources.atomic_cache_size << "), UINT64_C(" << resources.uram_size
        << ")\n"
        << "    };\n";
    if (decl->getNumParams()) {
      out << "    static const ::npu_package_argument_t __dayan_metadata[] = "
             "{\n";
      for (unsigned i = 0; i < decl->getNumParams(); ++i) {
        clang::dayan::PackageArgumentInfo argument =
            package_argument(decl->getParamDecl(i));
        if (argument.Kind == 2U) {
          out << "        { ::NPU_PACKAGE_ARG_BUFFER, 8U, "
              << argument.Alignment << "U, " << argument.Access << "U }";
        } else {
          out << "        { ::NPU_PACKAGE_ARG_VALUE, " << argument.Size
              << "U, 0U, 0U }";
        }
        out << (i + 1 == decl->getNumParams() ? "\n" : ",\n");
      }
      out << "    };\n";
    }
    out << "    ::npu_kernel_descriptor_t *__dayan_local =\n"
        << "        __atomic_load_n(&__dayan_descriptor, __ATOMIC_ACQUIRE);\n"
        << "    if (!__dayan_local) {\n"
        << "        while (__atomic_test_and_set(&__dayan_init_lock, "
           "__ATOMIC_ACQUIRE))\n"
        << "            ;\n"
        << "        __dayan_local = __atomic_load_n(&__dayan_descriptor, "
           "__ATOMIC_RELAXED);\n"
        << "        if (!__dayan_local) {\n"
        << "            int __dayan_status = ::npu_kernel_descriptor_create(\n"
        << "                ::__kernel_obj__, ::__kernel_obj_size__, \""
        << escape_string(mangled_name(decl)) << "\", ";
    if (decl->getNumParams())
      out << "__dayan_metadata, " << decl->getNumParams();
    else
      out << "nullptr, 0";
    out << ", &__dayan_resources, &__dayan_local);\n"
        << "            if (__dayan_status < 0) {\n"
        << "                __atomic_clear(&__dayan_init_lock, "
           "__ATOMIC_RELEASE);\n"
        << "                return __dayan_status;\n"
        << "            }\n"
        << "            __atomic_store_n(&__dayan_descriptor, __dayan_local, "
           "__ATOMIC_RELEASE);\n"
        << "        }\n"
        << "        __atomic_clear(&__dayan_init_lock, __ATOMIC_RELEASE);\n"
        << "    }\n";
    if (decl->getNumParams()) {
      out << "    ::npu_kernel_arg_t __dayan_args[" << decl->getNumParams()
          << "] = {};\n";
      for (unsigned i = 0; i < decl->getNumParams(); ++i) {
        const ParmVarDecl *parameter = decl->getParamDecl(i);
        if (buffer_parameter(parameter)) {
          out << "    ::npu_kernel_arg_buffer(&__dayan_args[" << i << "], "
              << argument_expression(parameter, i) << ", 0, "
              << buffer_access(parameter) << "U);\n";
        } else {
          out << "    ::npu_kernel_arg_value(&__dayan_args[" << i << "], "
              << argument_expression(parameter, i) << ", "
              << argument_size(parameter) << "U);\n";
        }
      }
      out << "    return ::npu_kernel_descriptor_launch(__dayan_local, "
             "__dayan_args, "
          << decl->getNumParams() << ", __dayan_launch_attrs);\n";
    } else {
      out << "    return ::npu_kernel_descriptor_launch(__dayan_local, "
             "nullptr, 0, "
             "__dayan_launch_attrs);\n";
    }
    out << "}\n#line " << after_line << " \"" << escape_string(input_name_)
        << "\"\n";
    return out.str();
  }

  void record_package_kernel(const FunctionDecl *decl) {
    clang::dayan::PackageKernelInfo kernel;
    const KernelResources &resources =
        kernel_resources_.at(decl->getNameAsString());
    kernel.Name = decl->getNameAsString();
    kernel.EntrySymbol = mangled_name(decl);
    kernel.MaxChildThreads = resources.max_child_threads;
    kernel.MaxTasksPerCore = resources.max_tasks_per_core;
    kernel.Flags = resources.flags;
    kernel.LsuTcsrCount = resources.lsu_tcsr_count;
    kernel.MatTcsrCount = resources.mat_tcsr_count;
    kernel.VecTcsrCount = resources.vec_tcsr_count;
    kernel.MacroTcsrCount = resources.macro_tcsr_count;
    kernel.AtomicCacheSize = resources.atomic_cache_size;
    kernel.UramSize = resources.uram_size;
    for (unsigned i = 0; i < decl->getNumParams(); ++i)
      kernel.Arguments.push_back(package_argument(decl->getParamDecl(i)));
    split_output_.Kernels.push_back(std::move(kernel));
  }

  bool validate_kernel(FunctionDecl *decl) {
    if (!decl->getIdentifier()) {
      diagnose(decl, "__kernel__ requires an ordinary named function");
      return false;
    }
    if (decl->getTemplatedKind() != FunctionDecl::TK_NonTemplate) {
      diagnose(decl, "__kernel__ function templates are not supported");
      return false;
    }
    if (decl->isVariadic()) {
      diagnose(decl, "__kernel__ functions cannot be variadic");
      return false;
    }
    if (!decl->getReturnType()->isVoidType()) {
      diagnose(decl, "__kernel__ functions must return void");
      return false;
    }
    if (decl->getNumParams() > 8) {
      diagnose(decl,
               "__kernel__ functions support at most 8 machine-word arguments");
      return false;
    }
    if (decl->getFormalLinkage() == clang::Linkage::Internal) {
      diagnose(decl, "__kernel__ functions must have external linkage");
      return false;
    }
    for (unsigned i = 0; i < decl->getNumParams(); ++i) {
      if (argument_expression(decl->getParamDecl(i), i).empty()) {
        diagnose(decl->getParamDecl(i),
                 "kernel parameter must be an integer, enum, pointer, "
                 "reference, float, or double");
        return false;
      }
    }
    return true;
  }

  void collect_function_edits() {
    std::set<const FunctionDecl *> validated;
    std::map<const FunctionDecl *, unsigned> definitions;
    for (FunctionDecl *decl : functions_) {
      const FunctionDecl *canonical = decl->getCanonicalDecl();
      Side side = function_side(decl);
      if (side == Side::Invalid) {
        diagnose(decl,
                 "function redeclarations have conflicting Dayan attributes");
        continue;
      }
      if (side == Side::Kernel && validated.insert(canonical).second) {
        if (!validate_kernel(decl))
          continue;
        for (const FunctionDecl *redecl : decl->redecls()) {
          if (redecl->isThisDeclarationADefinition())
            ++definitions[canonical];
        }
        if (definitions[canonical] != 1) {
          diagnose(
              decl,
              "__kernel__ requires exactly one definition in this source file");
          continue;
        }
        record_package_kernel(decl);
      }

      bool has_body = decl->isThisDeclarationADefinition();
      auto span = decl->hasSkippedBody() ? skipped_function_span(decl)
                                         : declaration_span(decl, !has_body);
      if (!span)
        continue;
      switch (side) {
      case Side::Both:
        break;
      case Side::Host:
        device_edits_.push_back({span->begin, span->end, {}});
        break;
      case Side::Device:
        host_edits_.push_back({span->begin, span->end, {}});
        break;
      case Side::Kernel:
        host_edits_.push_back(
            {span->begin, span->end, wrapper(decl, has_body)});
        break;
      case Side::Invalid:
        break;
      }
    }
  }

  void collect_variable_edits() {
    struct Group {
      std::size_t begin = std::numeric_limits<std::size_t>::max();
      std::size_t end = 0;
      Side side = Side::Both;
      VarDecl *representative = nullptr;
    };
    std::map<std::size_t, Group> groups;

    for (VarDecl *decl : variables_) {
      if (descriptor_variables_.count(decl) && decl->getBeginLoc().isMacroID())
        continue;
      Side side = annotation_side(decl);
      if (side == Side::Both) {
        diagnose(decl, "global variable requires an explicit __host__ or "
                       "__device__ attribute");
        continue;
      }
      if (side == Side::Kernel || side == Side::Invalid) {
        diagnose(
            decl,
            "global variable must use exactly one of __host__ or __device__");
        continue;
      }
      auto span = variable_statement_span(decl);
      if (!span)
        continue;
      Group &group = groups[span->end];
      group.begin = std::min(group.begin, span->begin);
      group.end = span->end;
      group.representative = decl;
      if (group.side == Side::Both)
        group.side = side;
      else if (group.side != side)
        group.side = Side::Invalid;
    }
    for (const auto &[unused, group] : groups) {
      (void)unused;
      if (group.side == Side::Invalid) {
        diagnose(
            group.representative,
            "variables in one declaration cannot target different Dayan sides");
        continue;
      }
      Edit edit{group.begin, group.end, {}};
      if (group.side == Side::Host)
        device_edits_.push_back(edit);
      else if (group.side == Side::Device)
        host_edits_.push_back(edit);
    }
  }

  std::string apply_edits(const std::string &original, std::vector<Edit> edits,
                          const char *side_name) {
    std::sort(edits.begin(), edits.end(),
              [](const Edit &left, const Edit &right) {
                if (left.begin != right.begin)
                  return left.begin > right.begin;
                return left.end > right.end;
              });
    std::string result = original;
    std::size_t previous_begin = original.size();
    for (const Edit &edit : edits) {
      if (edit.end > original.size() || edit.begin >= edit.end ||
          edit.end > previous_begin) {
        std::cerr << "dycc: error: overlapping " << side_name
                  << " source edits near byte " << edit.begin << "\n";
        output_.failed = true;
        return {};
      }
      result.replace(edit.begin, edit.end - edit.begin, edit.replacement);
      previous_begin = edit.begin;
    }
    return result;
  }

  ASTContext &context_;
  SourceManager &source_;
  const LangOptions &language_;
  SplitState &output_;
  clang::dayan::SplitOutput &split_output_;
  std::string input_name_;
  PrintingPolicy policy_;
  std::vector<FunctionDecl *> functions_;
  std::vector<VarDecl *> variables_;
  std::map<std::string, KernelResources> kernel_resources_;
  std::set<const VarDecl *> descriptor_variables_;
  std::vector<Edit> host_edits_;
  std::vector<Edit> device_edits_;
};

class SplitConsumer : public clang::ASTConsumer {
public:
  SplitConsumer(ASTContext &context, SplitState &output,
                clang::dayan::SplitOutput &split_output,
                const std::string &input_name)
      : visitor_(context, output, split_output, input_name) {}

  void HandleTranslationUnit(ASTContext &context) override {
    visitor_.TraverseDecl(context.getTranslationUnitDecl());
    visitor_.finish();
  }

  bool shouldSkipFunctionBody(Decl *decl) override {
    const auto *function = llvm::dyn_cast<FunctionDecl>(decl);

    return function && function_side(function) == Side::Host;
  }

private:
  SplitVisitor visitor_;
};

class SplitAction : public clang::ASTFrontendAction {
public:
  SplitAction(SplitState &output, clang::dayan::SplitOutput &split_output,
              std::string input_name)
      : output_(output), split_output_(split_output),
        input_name_(std::move(input_name)) {}

  std::unique_ptr<clang::ASTConsumer>
  CreateASTConsumer(CompilerInstance &compiler, llvm::StringRef) override {
    return std::make_unique<SplitConsumer>(compiler.getASTContext(), output_,
                                           split_output_, input_name_);
  }

  bool BeginSourceFileAction(CompilerInstance &compiler) override {
    compiler.getFrontendOpts().SkipFunctionBodies = true;
    return true;
  }

private:
  SplitState &output_;
  clang::dayan::SplitOutput &split_output_;
  std::string input_name_;
};

class SplitActionFactory : public clang::tooling::FrontendActionFactory {
public:
  SplitActionFactory(SplitState &output,
                     clang::dayan::SplitOutput &split_output,
                     std::string input_name)
      : output_(output), split_output_(split_output),
        input_name_(std::move(input_name)) {}

  std::unique_ptr<clang::FrontendAction> create() override {
    return std::make_unique<SplitAction>(output_, split_output_, input_name_);
  }

private:
  SplitState &output_;
  clang::dayan::SplitOutput &split_output_;
  std::string input_name_;
};

